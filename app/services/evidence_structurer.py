"""
Evidence-only deterministic finding structurer.

Builds LLM prompts from typed evidence fields (not raw notes) with hard caps.
Ensures all generated content is anchored to scanner evidence, preventing hallucinations.
"""

import json as _json
import logging
import re
from typing import Dict, Tuple

from app.services.template_parse import template_to_section_keys, template_all_table_row_labels
from app.services.llm_validation import validate_structured_output, get_strict_retry_instructions

log = logging.getLogger(__name__)

# Hard caps for evidence fields to prevent prompt bloat
MAX_TITLE = 200
MAX_DESCRIPTION = 2000
MAX_REMEDIATION = 1500
MAX_LOCATIONS = 20
MAX_RAW_HTTP_CHARS = 100_000  # cap for Raw HTTP Request/Response injection from artifacts

# System-owned fields that are set by clamps or from evidence artifacts, not generated by LLM
SYSTEM_OWNED_FIELDS = ["Affected Files", "Raw HTTP Request", "Raw HTTP Response"]


def _format_locations(locations: list[dict], max_count: int = MAX_LOCATIONS) -> str:
    """
    Format locations as readable list for LLM prompt.
    Excludes snippets (too large, not needed for generation).
    """
    if not locations:
        return "(no specific locations provided)"
    
    lines = []
    for loc in locations[:max_count]:
        file_path = loc.get("file", "")
        line_num = loc.get("line")
        if file_path:
            if line_num:
                lines.append(f"- {file_path}:{line_num}")
            else:
                lines.append(f"- {file_path}")
    
    if len(locations) > max_count:
        lines.append(f"... and {len(locations) - max_count} more locations")
    
    return "\n".join(lines) if lines else "(no specific locations provided)"


def _build_evidence_context(evidence: dict) -> str:
    """
    Build structured evidence prompt from typed fields.
    Safe access with defaults - evidence fields are optional.
    Includes scanner's original severity as a reference point.
    """
    # Safe access with defaults - malformed records will not crash
    rule_id = evidence.get('rule_id', 'unknown')[:100]
    tool = evidence.get('tool', 'unknown')[:50]
    title = evidence.get('title', '(no title)')[:MAX_TITLE]
    description = evidence.get('description', '(no description)')[:MAX_DESCRIPTION]
    remediation = evidence.get('remediation', '(no remediation)')[:MAX_REMEDIATION]
    locations = evidence.get('locations', [])
    
    # Extract scanner's original severity from payload (if available)
    original_severity = None
    payload = evidence.get('_payload_object')
    if payload and hasattr(payload, 'source'):
        original_severity = payload.source.original_severity
    
    evidence_context = f"""
EVIDENCE FROM SECURITY SCANNER:

Rule ID: {rule_id}
Tool: {tool}
Finding Title: {title}"""
    
    # Add scanner's original severity if available
    if original_severity:
        evidence_context += f"""
Scanner's Original Severity Assessment: {original_severity}

IMPORTANT: The scanner has security domain expertise. If you assign a different severity based on the rubric definitions below, you MUST explicitly explain in your Justification why the scanner's assessment should be adjusted. Default to respecting the scanner's expertise unless there is clear evidence supporting a different severity level.
"""
    
    evidence_context += f"""

Description:
{description}

Remediation:
{remediation}

Affected Locations:
{_format_locations(locations, max_count=MAX_LOCATIONS)}

Note: Code snippets are not included. Base your analysis on the description and remediation text only.
""".strip()
    
    return evidence_context


def structure_from_evidence(
    notes: str,
    evidence: dict,
    template_markdown: str,
    severity_rubric = None,
    llm_provider: str | None = None,
    llm_model: str | None = None,
    llm_base_url: str | None = None,
    llm_api_key_override: str | None = None,
    org_context: dict[str, str] | None = None,
    severity_criteria: dict[str, str] | None = None,
    preferred_language: str | None = None,
    extra_instructions: str | None = None,
    llm_timeout: float | None = None,
    sampling_params: dict | None = None,
    **kwargs
) -> Tuple[Dict[str, str], Dict[str, str]]:
    """
    Generate structured finding using ONLY typed evidence fields, no raw notes blob.
    
    Args:
        notes: Raw scanner output (stored in evidence, NOT passed to LLM)
        evidence: Deterministic evidence dict with typed fields
        template_markdown: Master template for section schema
        severity_rubric: For severity clamping (optional)
        llm_provider: LLM provider override
        llm_model: LLM model override
        llm_base_url: LLM base URL override
        llm_api_key_override: API key override
        org_context: Organization context (org_name, author, voice_style)
        severity_criteria: Severity definitions from template
        preferred_language: Output language preference
        extra_instructions: Additional LLM instructions
        
    Returns:
        Tuple of (structured_dict, debug_info)
    """
    from app.services.llm import chat_completion, get_model, is_llm_available
    from app.services.structurer import _get_key, _canonicalize_severity
    
    if not is_llm_available(provider_override=llm_provider, api_key_override=llm_api_key_override):
        raise ValueError(
            "LLM is not configured. Go to Settings > AI Provider to configure your API key and model. "
            "Supported providers: OpenAI, Anthropic, Gemini, Groq, Together, DeepSeek, Mistral, Ollama."
        )
    
    # Extract section schema from template (headings + all table row labels, e.g. Raw HTTP Request/Response)
    section_keys = list(template_to_section_keys(template_markdown))
    table_row_labels = template_all_table_row_labels(template_markdown)
    seen = {k.lower() for k in section_keys}
    for label in table_row_labels or []:
        if label and label.strip().lower() not in seen:
            section_keys.append(label.strip())
            seen.add(label.strip().lower())
    
    # Remove system-owned fields from required keys (model should NOT generate these)
    model_keys = [k for k in section_keys if k not in SYSTEM_OWNED_FIELDS]
    sections_str = "\n".join(f"- {h}" for h in model_keys)
    
    # Build severity instruction text
    if severity_criteria:
        criteria_lines = ["SEVERITY DEFINITIONS — Apply these criteria strictly from the master report template:\n"]
        for level in ["Critical", "High", "Medium", "Low", "Informational"]:
            if level in severity_criteria:
                criteria_lines.append(f"{level} — {severity_criteria[level]}")
        severity_text = "\n\n".join(criteria_lines)
    elif severity_rubric and severity_rubric.definitions:
        criteria_lines = ["SEVERITY DEFINITIONS — Apply these criteria strictly:\n"]
        for level in severity_rubric.allowed_labels:
            if level in severity_rubric.definitions:
                criteria_lines.append(f"{level} — {severity_rubric.definitions[level]}")
        severity_text = "\n\n".join(criteria_lines)
    else:
        # Use default severity definitions from structurer.py
        from app.services.structurer import SEVERITY_CRITERIA_SNIPPET
        severity_text = """
SEVERITY DEFINITIONS — Apply these criteria strictly. Use secure-coding judgment: do not downplay impact; assign the severity that accurately reflects exploitability and impact. When in doubt, prefer the higher severity that the evidence supports.

""" + "\n\n".join(f"{level} — {desc}" for level, desc in SEVERITY_CRITERIA_SNIPPET.items())
    
    # Build rubric injection if available
    rubric_text = ""
    if severity_rubric:
        rubric_text = f"\n\nSEVERITY LABELS — You MUST use ONLY these exact severity labels: {', '.join(severity_rubric.allowed_labels)}.\n"
        if severity_rubric.definitions:
            rubric_text += "Definitions:\n"
            for label in severity_rubric.allowed_labels:
                if label in severity_rubric.definitions:
                    rubric_text += f"- {label}: {severity_rubric.definitions[label]}\n"
    
    # PRE-LLM: Classify test artifacts and inject constraint if high confidence
    from app.services.evidence_clamps import classify_artifact_context
    
    classification = classify_artifact_context(evidence)
    test_constraint = ""
    
    if classification["is_test"] and classification["score"] >= 4:
        if classification["internal_only"]:
            test_constraint = "\n\nIMPORTANT: This evidence indicates a test artifact or test harness with only internal destinations (RFC1918/localhost). Severity must not exceed Informational."
        else:
            test_constraint = "\n\nIMPORTANT: This evidence indicates a test artifact or test harness. Severity must not exceed Low."
        
        log.info(f"Pre-LLM test constraint injected: score={classification['score']}, signals={classification['signals']}, internal_only={classification['internal_only']}")
    
    # Build evidence context (typed fields only, no raw notes)
    evidence_context = _build_evidence_context(evidence)
    
    # Build organization context
    org_text = ""
    if org_context:
        org_name = org_context.get("org_name", "").strip()
        author_name = org_context.get("author_name", "").strip()
        voice_style = org_context.get("voice_style", "").strip()
        if org_name or author_name or voice_style:
            org_parts = []
            if org_name:
                org_parts.append(f"Organization: {org_name}")
            if author_name:
                org_parts.append(f"Author: {author_name}")
            if voice_style:
                org_parts.append(f"Voice/Style: {voice_style}")
            org_text = "\n\n" + "\n".join(org_parts)
    
    # Build language instruction
    language_instruction = ""
    if preferred_language and preferred_language != "English":
        language_instruction = f"\n\nIMPORTANT: Write all narrative content in {preferred_language}. Technical identifiers (URLs, file paths, CVE/CWE/OWASP/CVSS IDs) should remain in English if present in evidence."
    
    # Build system prompt
    system_prompt = f"""You are a professional security analyst writing structured vulnerability reports. You will be given evidence from a security scanner and must format it into a structured JSON report.

{severity_text}{rubric_text}{test_constraint}

CRITICAL INSTRUCTIONS:
1. Return ONLY a JSON object with string values
2. Use ONLY these exact section names (case-sensitive):
{sections_str}
3. Do NOT include: {', '.join(SYSTEM_OWNED_FIELDS)} (these are system-managed)
4. Each field value must be plain narrative text - NO nested JSON objects or arrays
5. Do NOT use code fences (```) anywhere in your response
6. Do NOT stringify JSON and put it in a field value
7. For metadata fields (CWE, CVSS v3.1, OWASP, Affected Roles):
   - For CWE: suggest the most specific applicable CWE ID (e.g. CWE-79) based on the vulnerability type
   - For OWASP: suggest the applicable OWASP Top 10 2021 category (e.g. A03:2021)
   - For CVSS v3.1: only include if explicitly present in the evidence
   - Use sensible defaults for user-facing fields (e.g., "All Users" for Affected Roles)
8. For narrative fields: Write based on evidence; if evidence doesn't support a narrative section, write "Not provided in evidence"
9. Base your analysis ONLY on the evidence provided - do not invent file paths, URLs, or technical details
10. Preserve all technical identifiers from evidence (CVE, CWE, OWASP, CVSS IDs, file paths, URLs) verbatim if present{language_instruction}{org_text}

{extra_instructions or ""}

{evidence_context}

Return your response as a JSON object with the section names as keys and narrative text as values.""".strip()
    
    try:
        # Initial LLM call
        content = chat_completion(
            messages=[{"role": "user", "content": system_prompt}],
            provider_override=llm_provider,
            model_override=llm_model,
            base_url_override=llm_base_url,
            api_key_override=llm_api_key_override,
            timeout_override=llm_timeout,
            sampling_params=sampling_params,
        )
        
        # Strip markdown code fences if present
        content = re.sub(r'^```(?:json)?\s*\n', '', content, flags=re.MULTILINE)
        content = re.sub(r'\n```\s*$', '', content, flags=re.MULTILINE)
        content = content.strip()
        
        try:
            filled = _json.loads(content)
        except _json.JSONDecodeError as je:
            log.error("Failed to parse LLM JSON response: %s", je)
            raise ValueError(f"LLM returned invalid JSON: {je}")
        
        # Validate output (exclude system-owned fields from required keys)
        is_valid, validation_issues = validate_structured_output(
            filled,
            required_keys=model_keys,
            system_owned_keys=SYSTEM_OWNED_FIELDS
        )
        
        if not is_valid:
            # Retry exactly once with stricter instructions
            retry_instructions = get_strict_retry_instructions()
            retry_system = system_prompt + "\n\n" + retry_instructions
            
            log.warning("LLM output validation failed, retrying with strict instructions. Issues: %s", validation_issues)
            filled["_validation_flags"] = ["validation_failed_on_first_attempt"] + validation_issues
            
            retry_content = chat_completion(
                messages=[{"role": "user", "content": retry_system}],
                provider_override=llm_provider,
                model_override=llm_model,
                base_url_override=llm_base_url,
                api_key_override=llm_api_key_override,
                temperature=0.2,
                timeout_override=llm_timeout,
                sampling_params=sampling_params,
            )
            retry_content = re.sub(r'^```(?:json)?\s*\n', '', retry_content, flags=re.MULTILINE)
            retry_content = re.sub(r'\n```\s*$', '', retry_content, flags=re.MULTILINE)
            retry_content = retry_content.strip()
            
            try:
                retry_filled = _json.loads(retry_content)
            except _json.JSONDecodeError as je:
                log.error("Retry failed to parse JSON: %s", je)
                raise ValueError(f"LLM retry returned invalid JSON after validation failure. Original issues: {validation_issues}. Retry error: {je}")
            
            # Validate retry output
            retry_valid, retry_issues = validate_structured_output(
                retry_filled,
                required_keys=model_keys,
                system_owned_keys=SYSTEM_OWNED_FIELDS
            )
            
            if not retry_valid:
                # Fail fast - do not continue with malformed output
                log.error("LLM retry still invalid. Original issues: %s. Retry issues: %s", validation_issues, retry_issues)
                raise ValueError(
                    f"LLM output validation failed after retry. "
                    f"Original issues: {', '.join(validation_issues)}. "
                    f"Retry issues: {', '.join(retry_issues)}. "
                    "Raw output logged to DB only, not committed."
                )
            
            filled = retry_filled
            filled["_model_retry"] = True
            filled["_validation_flags"] = filled.get("_validation_flags", []) + ["retry_successful"]
        
        # Ensure all template sections exist with smart defaults
        # Table fields that should have defaults, not "Not provided in evidence"
        TABLE_FIELDS_WITH_DEFAULTS = {
            "Affected Roles": "All Users",
            "Affected Users": "All Users",
        }
        
        for key in section_keys:
            if key in SYSTEM_OWNED_FIELDS:
                continue  # Skip system-owned fields
            if key not in filled or not str(filled.get(key, "")).strip():
                # Use smart defaults for table/metadata fields
                if key in TABLE_FIELDS_WITH_DEFAULTS:
                    filled[key] = TABLE_FIELDS_WITH_DEFAULTS[key]
                else:
                    # For narrative sections, use explicit placeholder
                    filled[key] = "Not provided in evidence"
        
        # Ensure title field
        if "title" not in filled or not filled.get("title"):
            # Prefer Finding Title section when available
            if filled.get("Finding Title"):
                filled["title"] = str(filled.get("Finding Title")).strip().split("\n")[0]
            else:
                filled["title"] = evidence.get("title", "")[:MAX_TITLE]
        
        # Canonicalize severity (LOW-10: pass notes for inference when LLM left severity empty)
        # Rubric from master.docx is applied after by clamp_severity - it remains the final authority
        sev_key = _get_key(filled, "Severity")
        if sev_key:
            filled[sev_key] = _canonicalize_severity(str(filled.get(sev_key) or ""), notes=notes or "")
        
        debug_info = {
            "source": "evidence_deterministic",
            "provider": llm_provider or "openai",
            "model": get_model(
                provider_override=llm_provider,
                model_override=llm_model,
                base_url_override=llm_base_url,
            ),
            "flow_version": "deterministic_v1"
        }
        
        # MED-14: Reorder output to match template section order
        # LLM returns a plain dict with arbitrary order; we want template order preserved
        ordered_filled = {}
        for key in section_keys:
            if key in filled:
                ordered_filled[key] = filled[key]
        
        # Preserve any extra keys not in template (e.g., _validation_flags, _model_retry)
        for key in filled:
            if key not in ordered_filled:
                ordered_filled[key] = filled[key]
        
        # Inject Raw HTTP Request/Response from evidence artifacts (Burp etc.) — system-owned, not LLM-generated
        payload = evidence.get("_payload_object") if evidence else None
        if payload and getattr(payload, "artifacts", None):
            artifacts = payload.artifacts
            raw_req = artifacts.get("http_request") or ""
            raw_resp = artifacts.get("http_response") or ""
            if isinstance(raw_req, str) and raw_req.strip():
                ordered_filled["Raw HTTP Request"] = raw_req[:MAX_RAW_HTTP_CHARS]
            if isinstance(raw_resp, str) and raw_resp.strip():
                ordered_filled["Raw HTTP Response"] = raw_resp[:MAX_RAW_HTTP_CHARS]
        
        return ordered_filled, debug_info
        
    except Exception as e:
        log.exception("Evidence structurer failed: %s", e)
        raise ValueError(f"Evidence-based structuring failed: {e}")
